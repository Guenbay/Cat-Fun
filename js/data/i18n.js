export const UI = { de: DE, en: EN, tr: TR };

/** Erzeugt eine Übersetzungsfunktion für eine Sprache. Fällt auf Deutsch zurück. */
export function translator(lang) {
  const dict = UI[lang] || UI.de;
  return (key, vars) => {
    let s = dict[key] ?? UI.de[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}
